import pandas as pd
import matplotlib.pyplot as plt
import os
os.makedirs("results", exist_ok=True)
df = pd.read_csv("results/cleaned.csv")
summary = pd.read_csv("results/summary.csv")
plt.figure()
plt.bar(summary["Группа"], summary["mean_avg"])
plt.title("Средний результат по группам. Вариант 11")
plt.xlabel("Группа")
plt.ylabel("Среднее")
plt.grid(axis="y")
plt.tight_layout()
plt.savefig("results/group_average.png")
plt.close()
plt.figure()
plt.plot(df["ID"], df["Среднее"], marker="o")
plt.title("Средние результаты участников")
plt.xlabel("ID")
plt.ylabel("Среднее")
plt.xticks(df["ID"])
plt.tight_layout()
plt.savefig("results/participants.png")
plt.close()
plt.figure()
plt.bar(summary["Группа"], summary["admitted"])
plt.title("Количество допущенных по группам")
plt.xlabel("Группа")
plt.ylabel("Число допущенных")
plt.tight_layout()
plt.savefig("results/admission.png")
plt.close()
print("Три графика сохранены")